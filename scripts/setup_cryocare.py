"""Opt-in modern cryoCARE installation. Never changes RELION scientific sources."""
import json, os, pathlib, shlex, shutil, subprocess

SCRIPTS = ('cryoCARE_train.py', 'cryoCARE_predict.py', 'cryoCARE_extract_train_data.py')
URL = 'https://github.com/GavinR1/cryoCARE_pip.git'
BRANCH = 'make_cryocare_great_again'

def run(args, **kwargs):
    return subprocess.check_output([str(x) for x in args], text=True, **kwargs)

def hooks(prefix):
    values = {'LD_LIBRARY_PATH': str(prefix/'lib'), 'TF_CUDA_CLANG': '1',
              'TF_XLA_FLAGS': '--tf_xla_auto_jit=2', 'XLA_FLAGS': '--xla_gpu_cuda_data_dir='+str(prefix)}
    activate, deactivate, cactivate, cdeactivate = [], [], [], []
    for key, value in values.items():
        old = 'RELIONDELUXE_SAVED_'+key
        flag = old+'_SET'
        activate += [f'export {flag}="${{{key}+yes}}"', f'export {old}="${{{key}-}}"',
                     f'export {key}='+shlex.quote(value)+(f'"${{{key}:+:${key}}}"' if key=='LD_LIBRARY_PATH' else '')]
        deactivate += [f'if [ "${{{flag}-}}" = yes ]; then export {key}="${{{old}-}}"; else unset {key}; fi', f'unset {old} {flag}']
        cactivate += [f'if ( $?{key} ) then', f'  setenv {flag} yes', f'  setenv {old} "${key}"', 'else', f'  setenv {flag} no', f'  setenv {old} ""', 'endif', f'setenv {key} '+shlex.quote(value)]
        if key=='LD_LIBRARY_PATH':
            cactivate += [f'if ( "${old}" != "" ) setenv {key} "${key}:${old}"']
        cdeactivate += [f'if ( $?{flag} ) then', f'  if ( "${flag}" == "yes" ) then', f'    setenv {key} "${old}"', '  else', f'    unsetenv {key}', '  endif', f'  unsetenv {flag}', f'  unsetenv {old}', 'endif']
    return {'activate.d/reliondeluxe_cryocare.sh': '\n'.join(activate)+'\n',
            'deactivate.d/reliondeluxe_cryocare.sh': '\n'.join(deactivate)+'\n',
            'activate.d/reliondeluxe_cryocare.csh': '\n'.join(cactivate)+'\n',
            'deactivate.d/reliondeluxe_cryocare.csh': '\n'.join(cdeactivate)+'\n'}

def install(root, conda_executable=None, relion_env='relion-5.1'):
    conda = conda_executable or os.environ.get('CONDA_EXECUTABLE') or os.environ.get('CONDA_EXE')
    if not conda and os.environ.get('CONDA_INSTALL'):
        conda = str(pathlib.Path(os.environ['CONDA_INSTALL'])/'bin/conda')
    conda = conda or shutil.which('conda')
    if not conda: raise RuntimeError('Conda not found. Set CONDA_EXECUTABLE or pass --conda-executable.')
    conda = pathlib.Path(conda).resolve()
    envs = [pathlib.Path(x) for x in json.loads(run([conda,'env','list','--json']))['envs']]
    relion = next((x for x in envs if x.name==relion_env or str(x)==relion_env), None)
    if relion is None: raise RuntimeError('RELION Conda environment not found: '+relion_env)
    base = pathlib.Path(json.loads(run([conda,'info','--json']))['root_prefix'])
    shell = base/'etc/profile.d/conda.sh'
    if not shell.is_file(): raise RuntimeError('Missing Conda shell initialization: '+str(shell))
    folder = root/'relion_cryocare_wrappers'
    marker = folder/'.reliondeluxe-managed'
    if folder.exists() and not marker.is_file():
        raise RuntimeError('Refusing to replace an unmanaged directory: '+str(folder)+'. Rename it and retry.')
    folder.mkdir(exist_ok=True); marker.write_text('RelionDeLuxe modern cryoCARE\n')
    repo = folder/'cryoCARE_pip'
    if not repo.exists():
        subprocess.run(['git','clone','--branch',BRANCH,'--single-branch',URL,str(repo)],check=True)
    else:
        if run(['git','-C',repo,'remote','get-url','origin']).strip()!=URL:
            raise RuntimeError('Unexpected cryoCARE repository origin')
        print('Reusing checked-out cryoCARE source (no automatic branch update).',flush=True)
    modern = next((x for x in envs if x.name=='cryocare-modern'),None)
    if modern is None:
        subprocess.run([str(conda),'create','--yes','--name','cryocare-modern','python=3.10','pip'],check=True)
        envs = json.loads(run([conda,'env','list','--json']))['envs']
        modern = next(pathlib.Path(x) for x in envs if pathlib.Path(x).name=='cryocare-modern')
    # Do not overwrite unrelated hooks, even when their filenames happen to match.
    for name in hooks(modern):
        dest=relion/'etc/conda'/name
        if dest.exists() and not dest.read_text().startswith('# Generated by RelionDeLuxe\n'):
            raise RuntimeError('Refusing to overwrite an unmanaged Conda hook: '+str(dest))
    python = modern/'bin/python'
    cmd = [str(conda),'run','--no-capture-output','--prefix',str(modern)]
    for args in ([str(python),'-m','pip','install','-r','requirements-gpu.txt'], [str(python),'-m','pip','check'],
                 [str(python),'-c','import tensorflow as tf; g=tf.config.list_physical_devices("GPU"); print("Detected GPUs:",g); print("WARNING: no GPU visible on this host" if not g else "GPU detection completed; validate training on the compute host.")']):
        subprocess.run(cmd+args,cwd=repo,check=True)
    for name in SCRIPTS:
        if not (modern/'bin'/name).is_file(): raise RuntimeError('Missing installed script: '+name)
    wrapper = '#!/bin/bash\nset -e\nsource '+shlex.quote(str(shell))+'\nconda activate '+shlex.quote(str(modern))+'\n'
    wrapper += hooks(modern)['activate.d/reliondeluxe_cryocare.sh']
    wrapper += 'SCRIPT_NAME=$(basename "$0")\ncase "$SCRIPT_NAME" in\n  '+ '|'.join(SCRIPTS)+') ;;\n  *) echo "Invoke a cryoCARE script symlink" >&2; exit 2 ;;\nesac\n'
    wrapper += 'exec '+shlex.quote(str(python))+' '+shlex.quote(str(modern/'bin'))+'/$SCRIPT_NAME "$@"\n'
    (folder/'run_in_env.sh').write_text(wrapper); (folder/'run_in_env.sh').chmod(0o755)
    for name in SCRIPTS:
        link=folder/name
        if link.is_symlink(): link.unlink()
        elif link.exists(): raise RuntimeError('Refusing to overwrite non-symlink: '+str(link))
        link.symlink_to('run_in_env.sh')
    for name, content in hooks(modern).items():
        dest=relion/'etc/conda'/name; dest.parent.mkdir(parents=True,exist_ok=True)
        dest.write_text('# Generated by RelionDeLuxe\n'+content)
    config={'cryocare_path':str(folder),'revision':run(['git','-C',repo,'rev-parse','HEAD']).strip(),'environment':str(modern)}
    temporary=root/'cryocare-install.json.tmp'; temporary.write_text(json.dumps(config,indent=2)+'\n'); temporary.replace(root/'cryocare-install.json')
    print('Modern cryoCARE wrappers ready: '+str(folder)+'\nReactivate '+relion_env+' and restart RelionDeLuxe.',flush=True)
