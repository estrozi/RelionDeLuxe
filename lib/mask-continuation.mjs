import {isDyna,validateDynaContinuation} from './dynamight-continuation.mjs';
const refinements=new Set(['relion.refine3d','relion.class3d']);
const reference=value=>typeof value==='string'?value.match(/^\$\{(jobN(?:\+[1-9]\d*)?)\}(.+)$/):null;
export const checkpointName=name=>typeof name==='string'&&/^run_it\d+_optimiser\.star$/.test(name);
// Only the known two-step mask feedback pattern is unfolded. Other cycles stay errors.
export function unfoldMaskCycles(template){
 const steps=template.steps;if(!Array.isArray(steps))return [];
 const notes=[];
 for(const a of [...steps]){
  if(!refinements.has(a.type)||a.continuation||!a.values)continue;
  const mask=reference(a.values.fn_mask),b=mask&&steps.find(s=>s.id===mask[1]&&s.type==='relion.maskcreate');
  const map=reference(b?.values?.fn_in);if(!b||!map||map[1]!==a.id)continue;
  if(mask[2]!=='mask.mrc'||!/\.mrc$/.test(map[2]))throw Error(a.id+': unsupported mask feedback filenames.');
  if(a.type==='relion.class3d'&&!/^run_it\d+_class\d+\.mrc$/.test(map[2]))throw Error(a.id+': classification mask input must be a run_itNNN_classNNN.mrc map.');
  if(/--(?:solvent_mask|continue|o)(?:\s|=|$)/.test(a.values.other_args||''))throw Error(a.id+': remove conflicting mask/continuation/output overrides from Additional arguments before unfolding.');
  const explicit=reference(a.values.fn_cont),inferred=map[2].match(/^run_it(\d+)_.*\.mrc$/);
  let checkpoint=a.captureCheckpoint||(explicit?.[1]===a.id?explicit[2]:null)||(inferred?'run_it'+inferred[1]+'_optimiser.star':null);
  if(!checkpointName(checkpoint))throw Error(a.id+' ↔ '+b.id+': mask feedback detected, but its optimiser checkpoint cannot be inferred. Set captureCheckpoint to an explicit run_itNNN_optimiser.star in Edit JSON, then validate.');
  const iteration=Number(checkpoint.match(/_it(\d+)_/)[1]);if(!Number.isSafeInteger(iteration)||iteration<1)throw Error('Continuation checkpoint iteration must be positive.');
  let number=1;while(steps.some(s=>s.id==='jobN+'+number))number++;
  const c=structuredClone(a);c.id='jobN+'+number;c.title=(a.title||a.type)+' · clone continuation';delete c.captureCheckpoint;
  c.continuation={source:a.id,checkpoint};c.values.fn_cont='${'+a.id+'}'+checkpoint;
  a.values.fn_cont='';a.values.fn_mask='';delete a.captureCheckpoint;
  if(a.type==='relion.class3d'){
   a.values.nr_iter=String(iteration);
   // The mask must use an output generated by the initial phase, not C's later iteration.
   if(/^run_it\d+_class\d+\.mrc$/.test(map[2]))b.values.fn_in='${'+a.id+'}'+map[2].replace(/^run_it\d+_/,checkpoint.replace('_optimiser.star','')+'_');
  }
  if(a.type==='relion.refine3d')a.values.do_solvent_fsc='No';
  // B consumes the unmasked phase. All other existing consumers use C's masked result.
  for(const consumer of steps){if(consumer===a||consumer===b)continue;for(const [key,value]of Object.entries(consumer.values||{}))if(typeof value==='string')consumer.values[key]=value.split('${'+a.id+'}').join('${'+c.id+'}');}
  steps.push(c);
  notes.push('Unfolded '+a.id+' ↔ '+b.id+' into an unmasked run → mask creation → independent clone continuation from '+checkpoint+'. Review the initial-run settings, checkpoint availability and continuation iteration target. Classification first-phase iterations and its mask-input map are aligned with this checkpoint. Later consumers now use the masked clone.');
 }
 return notes;
}
export function validateContinuation(step,byId){
 if(!step.continuation)return;
 if(isDyna(step.type))return validateDynaContinuation(step,byId);
 const c=step.continuation,source=byId.get(c.source);
 if(!refinements.has(step.type)||!source||source.type!==step.type||source.id===step.id||source.continuation||!checkpointName(c.checkpoint))throw Error(step.id+': invalid clone continuation source or checkpoint.');
 const expected='${'+c.source+'}'+c.checkpoint;
 if(step.values.fn_cont!==expected)throw Error(step.id+': Continue from here must be '+expected+'. Edit the clone checkpoint control to change it.');
}
